// @requires errors schema util template ai-router runtime
//
// WF-02b Template generation. HR describes the email it wants; the model
// returns an HTML template with merge fields. The result lands INACTIVE — a
// human activates it after previewing, so a bad generation cannot reach a
// candidate.

const started = nowIso();
const correlationId = newCorrelationId('WF-02B');
const WORKFLOW = 'WF-02b Template';

let env = {};
try { env = $env || {}; } catch (_e) { env = {}; }

const request = (() => {
  try { return $('Verify Request').first().json || {}; } catch (_e) { return {}; }
})();

const store = $getWorkflowStaticData('global');
store.quota = store.quota || {};

const ALLOWED_FIELDS = ['first_name', 'name', 'job_role', 'category', 'company_name', 'hr_name', 'hr_signature', 'ai_body'];

try {
  const config = parseConfig(rowsOf($('Read Config').all()));
  const ledger = new QuotaLedger(store.quota);
  const router = new AiRouter({ http: makeHttp(this, { timeout: 60000 }), keys: apiKeys(env), ledger });

  const user = [
    `Company: ${config.company_name || 'the company'}`,
    `Purpose: ${request.purpose || 'initial outreach to a job applicant'}`,
    `Tone: ${request.tone || 'warm, professional, concise'}`,
    request.job_role ? `Role: ${request.job_role}` : '',
    request.notes ? `Extra instructions: ${String(request.notes).slice(0, 500)}` : '',
    '',
    'Produce a reusable HTML email template.',
    'Return JSON only: {"subject": "...", "html": "...", "name": "..."}',
    'Rules:',
    `- The only merge fields allowed are: ${ALLOWED_FIELDS.map((f) => `{{${f}}}`).join(' ')}`,
    '- Include {{ai_body}} on its own line where per-candidate text should be generated later.',
    '- Allowed tags: <p> <br> <strong> <em> <ul> <li> <a>. No <style>, no <script>, no CSS, no tables.',
    '- Every tag must be closed. The output is parsed and rejected if it is not.',
    '- Open with a greeting using {{first_name}} and close with {{hr_signature}}.',
    '- "name" is a short human label for this template, max 40 characters.',
  ].filter(Boolean).join('\n');

  const res = await router.complete({
    task: 'generate_template',
    system: 'You produce clean, email-client-safe HTML templates. You return JSON only.',
    user,
    json: true,
    temperature: 0.6,
    maxTokens: 1500,
    schemaCheck: (j) => {
      if (!j || typeof j.html !== 'string' || typeof j.subject !== 'string') return { ok: false, reason: 'missing subject or html' };
      const structure = validateHtml(j.html);
      if (!structure.ok) return { ok: false, reason: structure.problems.join(' ') };
      const unknown = extractFields(j.html + ' ' + j.subject).filter((f) => !ALLOWED_FIELDS.includes(f));
      if (unknown.length) return { ok: false, reason: `invented merge fields: ${unknown.join(', ')}` };
      return { ok: true };
    },
  });

  const now = nowIso();
  const template_rows = [{
    template_id: `TPL-${randomId(6)}`,
    name: String(res.json.name || request.name || 'Generated template').slice(0, 40),
    job_role: request.job_role || '',
    category: request.category || '',
    stage: request.stage || 'outreach',
    subject: res.json.subject,
    html: fitCell(res.json.html),
    source: 'ai',
    is_active: 'FALSE',
    is_default: 'FALSE',
    prompt_version: 'generate-template.v1',
    created_at: now,
    updated_at: now,
  }];

  const env0 = envelope({
    workflow: WORKFLOW, correlationId, trigger: 'webhook', started,
    items_in: 1, ok: [{ template_id: template_rows[0].template_id }],
    warnings: res.warnings,
    notes: `Generated by ${res.routeKey}. Saved INACTIVE — preview and activate it in the dashboard.`,
  });

  store.quota = ledger.snapshot();
  return [{ json: { ...env0, template_rows, preview: template_rows[0], error_rows: [], runlog_rows: [runLogRow(env0)] } }];
} catch (err) {
  const e = toAppError(err);
  const env0 = envelope({ workflow: WORKFLOW, correlationId, trigger: 'webhook', started, failed: [{ code: e.code, message: e.message }], notes: e.hint });
  return [{ json: { ...env0, template_rows: [], error_rows: [errorRow({ correlationId, workflow: WORKFLOW, node: 'Generate Template', error: e })], runlog_rows: [runLogRow(env0)] } }];
}
